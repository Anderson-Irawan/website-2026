<?php
/* ============================================
   sitemap.xml

   .htaccess points /sitemap.xml here, so the sitemap lists whatever is
   in Sanity at the moment Google asks for it. Publish a project and it
   is in the next crawl with nothing to regenerate.

   If Sanity is unreachable and the cache is cold, the four fixed pages
   are still listed. A short sitemap is fine; a broken one is not.
   ============================================ */

require __DIR__ . '/lib/sanity.php';

header('Content-Type: application/xml; charset=utf-8');

$site = 'https://doubledashcreative.com';

/* lastmod for the hand-written pages is just when the file last changed */
$fixed = array(
    array('/',         'index.html'),
    array('/about',    'about.html'),
    array('/contact',  'contact.html'),
);

function url_entry($loc, $lastmod)
{
    return "  <url>\n"
         . '    <loc>' . e($loc) . "</loc>\n"
         . '    <lastmod>' . e($lastmod) . "</lastmod>\n"
         . "  </url>\n";
}

/* the ?> is split so no php parser, however old or oddly configured,
   can mistake the xml declaration for the end of this script */
echo '<?xml version="1.0" encoding="UTF-8"?' . ">\n";
echo "<!-- Generated by sitemap.php. Case study urls come from Sanity, so\n";
echo "     this file never goes stale and is not edited by hand. -->\n";
echo '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">' . "\n\n";

foreach ($fixed as $page) {
    $file = __DIR__ . '/' . $page[1];
    $mod  = is_file($file) ? date('Y-m-d', filemtime($file)) : date('Y-m-d');
    echo url_entry($site . $page[0], $mod);
}

$projects = sanity_projects();

if ($projects) {
    echo "\n";
    foreach ($projects as $slug => $p) {
        $mod = !empty($p['_updatedAt'])
            ? substr($p['_updatedAt'], 0, 10)
            : date('Y-m-d');
        echo url_entry($site . '/work/' . $slug, $mod);
    }
}

echo "\n</urlset>\n";
